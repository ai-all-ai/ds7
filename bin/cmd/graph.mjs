#!/usr/bin/env node
// Site graph: a generated map of the project (routes, components, composables, data, styles, server) so an agent or a person can find what uses what
// without opening files. Nuxt auto-imports most of it, so the dependencies are not visible in the source; this graph is where they are written down.
//   ds7 graph                       write docs/SITE-GRAPH.md and, when docs/ARCHITECTURE.md has the markers, the placement table inside it
//   ds7 graph --check                 fail when either is out of date (part of check:strict)
//   ds7 graph --uses UiButton     who uses a component, composable, data file or text section (`home.timeValue`)
//   ds7 graph --of /about    what a page or component is made of, as a tree
//   ds7 graph --css btn        which stylesheet defines a class, and which components have it as root
//   ds7 graph --budget 1500   the most used files first, cut at about 1500 tokens: the map to give an agent that has little room
//   ds7 graph --stats         how large the map is next to the files it replaces (tokens are estimated as characters / 4)
import fs from 'node:fs';
import path from 'node:path';
import { listFiles, ROOT } from '../lib/project.mjs';
import { buildGraph } from '../lib/graph-model.mjs';
import { loadConfig } from '../lib/config.mjs';

const cfg = loadConfig();

const OUT = 'docs/SITE-GRAPH.md',
  ARCH = 'docs/ARCHITECTURE.md';
const [BEGIN, END] = ['<!-- placement:begin -->', '<!-- placement:end -->'];
const args = process.argv.slice(2);
const flag = (k) => {
  const i = args.indexOf(`--${k}`);
  return i > -1 ? args[i + 1] : undefined;
};
const g = buildGraph(listFiles());
const nodes = [...g.nodes.values()];
const ofKind = (...k) =>
  nodes.filter((n) => k.includes(n.kind)).sort((a, b) => a.id.localeCompare(b.id));
const stem = (id) => path.basename(id, path.extname(id));
const label = (n) =>
  n.kind === 'component'
    ? n.name
    : n.kind === 'page'
      ? n.route
      : ['composable', 'util', 'data'].includes(n.kind)
        ? stem(n.id)
        : n.id.replace(/^app\//, '');
const list = (arr, max = 8) =>
  arr.length <= max ? arr.join(', ') : `${arr.slice(0, max).join(', ')} +${arr.length - max}`;
const targets = (n, ...kinds) =>
  [...n.uses].map((id) => g.nodes.get(id)).filter((x) => x && kinds.includes(x.kind));
const usedBy = (n) =>
  g.usedBy
    .get(n.id)
    .map((id) => g.nodes.get(id))
    .sort((a, b) => label(a).localeCompare(label(b)));

// what a node itself depends on, in one line
function deps(n, { withComponents = true } = {}) {
  const parts = [];
  const c = targets(n, 'component').map(label).sort();
  if (withComponents && c.length) parts.push(`uses ${list(c, 16)}`);
  const f = targets(n, 'composable', 'util').map(label).sort();
  if (f.length) parts.push(`fn ${list(f)}`);
  const d = targets(n, 'data').map(label).sort();
  if (d.length) parts.push(`data ${list(d)}`);
  if (n.i18n.size) parts.push(`text ${list([...n.i18n].sort(), 4)}`);
  if (n.css.length) parts.push(`css ${n.css.join('+')} .${n.rootClass}`);
  else if (n.scoped) parts.push('css scoped');
  if (n.dynamic) parts.push('dynamic <component :is>');
  return parts.join(' · ');
}
const by = (n) => {
  const u = usedBy(n);
  return u.length
    ? ` · by ${u.length > 6 ? `${u.length} (--uses ${label(n)})` : u.map(label).join(', ')}`
    : '';
};

// the examples in the header name things this project has, so an agent can run them as written
function examples() {
  const comps = ofKind('component').sort(
    (a, b) => g.usedBy.get(b.id).length - g.usedBy.get(a.id).length || a.name.localeCompare(b.name),
  );
  const routes = ofKind('page')
    .map((n) => n.route)
    .filter((r) => !r.includes('['));
  const route = routes.filter((r) => r !== '/').sort((a, b) => a.length - b.length)[0] ?? routes[0];
  const styled = comps.find((n) => n.css.length && n.rootClass);
  return {
    uses: comps[0]?.name ?? 'UiButton',
    of: route ?? '/about',
    css: styled?.rootClass ?? 'btn',
  };
}

function render() {
  const L = [];
  const ex = examples();
  L.push(
    '# Site graph',
    '',
    'Generated by `ds7 graph` from the source tree; do not edit by hand. `ds7 graph --check` fails when it is out of date.',
    'Nuxt auto-imports components (by folder-prefixed name), composables and utils, so these links are not written as imports in the files: this map is where they are.',
    '',
    `Ask instead of reading files: \`ds7 graph --uses ${ex.uses}\` (who uses it), \`ds7 graph --of ${ex.of}\` (what a page is made of), \`ds7 graph --css ${ex.css}\` (which stylesheet defines a class). Where each kind of file lives: \`docs/ARCHITECTURE.md\`.`,
    '',
  );
  L.push(`## Routes (${ofKind('page').length})`, '');
  for (const n of ofKind('page').sort(
    (a, b) => a.route.length - b.route.length || a.route.localeCompare(b.route),
  ))
    L.push(`- \`${n.route}\` · ${n.id}${n.seo ? ` · seo \`${n.seo}\`` : ''} · ${deps(n)}`);
  const shell = ofKind('app', 'layout');
  L.push('', `## Shell (${shell.length})`, '');
  for (const n of shell) L.push(`- ${n.id} · ${deps(n) || 'no dependencies'}`);
  const comps = ofKind('component');
  L.push('', `## Components (${comps.length})`);
  for (const dir of [...new Set(comps.map((n) => n.id.split('/')[2]))]) {
    const group = comps.filter((n) => n.id.split('/')[2] === dir);
    L.push('', `### ${dir} (${group.length})`, '');
    for (const n of group) L.push(`- ${n.name} · ${deps(n)}${by(n)}`);
  }
  L.push('', '## Composables and utils', '');
  for (const n of ofKind('composable', 'util'))
    L.push(
      `- ${label(n)} (${n.id.replace(/^app\//, '')}) · ${deps(n) || 'no dependencies'}${by(n)}`,
    );
  L.push('', '## Data and text', '');
  for (const n of ofKind('data'))
    L.push(`- ${n.id.replace(/^app\//, '')}${n.uses.size ? ` · ${deps(n)}` : ''}${by(n)}`);
  for (const n of ofKind('i18n'))
    L.push(
      `- ${n.id} · read as \`messages.<section>.<group>\`; find the readers of a group with \`--uses <section.group>\``,
    );
  L.push(
    '',
    '## Styles',
    '',
    `Entry \`app/assets/css/main.css\`; order of imports: ${g.cssOrder.map((f) => `${path.basename(f)} (${g.nodes.get(f)?.lines ?? '?'})`).join(', ')}.`,
  );
  const server = ofKind('server');
  L.push('', `## Server (${server.length})`, '');
  for (const n of server) L.push(`- ${n.id} · ${deps(n) || 'no dependencies'}`);
  return `${L.join('\n')}\n`;
}

function placement() {
  const { rules, imports } = cfg.layout;
  return [
    '| Path | What lives here |',
    '| --- | --- |',
    ...rules.map((r) => `| \`${r.path}\` | ${r.what} |`),
    '',
    'Import rules (`ds7 layout` enforces them):',
    '',
    ...imports.map(
      (i) =>
        `- \`${i.from}\` does not import ${i.deny.map((d) => `\`${d}\``).join(', ')}: ${i.why}.`,
    ),
  ].join('\n');
}
// the placement table is written between two markers of docs/ARCHITECTURE.md; without the file or the markers only the graph is written
function withPlacement(arch) {
  const i = arch.indexOf(BEGIN),
    j = arch.indexOf(END);
  return i < 0 || j < i
    ? null
    : `${arch.slice(0, i + BEGIN.length)}\n${placement()}\n${arch.slice(j)}`;
}

// queries
function findNode(q) {
  const hit = nodes.filter(
    (n) => n.kind !== 'css' && [label(n), n.id, n.id.replace(/^app\//, ''), n.route].includes(q),
  );
  return hit.length
    ? hit
    : nodes.filter(
        (n) => n.id.endsWith(`/${q}`) || n.id.endsWith(`/${q}.vue`) || n.id.endsWith(`/${q}.ts`),
      );
}
function queryUses(q) {
  const found = findNode(q);
  const text = nodes.filter((n) =>
    [...n.i18n].some((k) => k === q || k.startsWith(`${q}.`) || q.startsWith(`${k}.`)),
  );
  if (!found.length && !text.length) {
    console.log(
      `Nothing named "${q}". Try a component name, a route, a data or composable name, or a text section like home.timeValue.`,
    );
    process.exit(1);
  }
  for (const n of found) {
    const u = usedBy(n);
    console.log(
      `${label(n)} (${n.id}) is used by ${u.length}${u.length ? ':' : ' (nothing; dead or entered by the framework)'}`,
    );
    for (const x of u) console.log(`  ${label(x)}  ${x.id}`);
  }
  if (text.length) {
    console.log(`text section ${q} is read by:`);
    for (const n of text) console.log(`  ${label(n)}  ${n.id}`);
  }
}
function queryOf(q) {
  const [root] = findNode(q);
  if (!root) {
    console.log(`Nothing named "${q}". Use a route (/about) or a component name.`);
    process.exit(1);
  }
  const seen = new Set();
  const walk = (n, depth) => {
    const rest = deps(n, { withComponents: false });
    console.log(
      `${'  '.repeat(depth)}${label(n)}${rest ? `  [${rest}]` : ''}${seen.has(n.id) ? '  (above)' : ''}`,
    );
    if (seen.has(n.id)) return;
    seen.add(n.id);
    for (const c of targets(n, 'component').sort((a, b) => label(a).localeCompare(label(b))))
      walk(c, depth + 1);
  };
  walk(root, 0);
}
function queryCss(q) {
  const cls = q.replace(/^\./, '');
  const files = [...g.cssClasses].filter(([, set]) => set.has(cls)).map(([f]) => f);
  console.log(
    files.length
      ? `.${cls} is defined in ${files.join(', ')}`
      : `.${cls} is defined in no stylesheet of app/assets/css`,
  );
  for (const n of nodes.filter((x) => x.rootClass === cls))
    console.log(`  root class of ${label(n)} (${n.id})`);
}

const tokens = (s) => Math.ceil(s.length / 4);
// the most used files first (a route ranks by how much it is made of), until the budget is spent
function queryBudget(limit) {
  if (!Number.isInteger(limit) || limit < 1) {
    console.error('graph: --budget needs a number of tokens, e.g. --budget 1500');
    process.exit(1);
  }
  const rank = (n) => (n.kind === 'page' ? n.uses.size : usedBy(n).length);
  const ranked = nodes
    .filter((n) => !['css', 'i18n'].includes(n.kind))
    .sort((a, b) => rank(b) - rank(a) || a.id.localeCompare(b.id));
  const head = `Site graph, most used first (budget ${limit} tokens). Everything: ${OUT}. Ask: ds7 graph --uses X, --of X, --css X.`;
  const out = [head];
  let spent = tokens(head);
  for (const n of ranked) {
    const line = `- ${label(n)} (${n.id}) · ${deps(n) || 'no dependencies'}${by(n)}`;
    if (spent + tokens(line) > limit) break;
    out.push(line);
    spent += tokens(line);
  }
  out.push(`(${out.length - 1} of ${ranked.length} files shown, about ${spent} tokens)`);
  console.log(out.join('\n'));
}
function queryStats() {
  const map = tokens(render());
  const source = nodes.reduce((sum, n) => {
    const f = path.join(ROOT, n.id);
    return sum + (fs.existsSync(f) ? fs.statSync(f).size : 0);
  }, 0);
  console.log(
    `graph: the map is about ${map} tokens; the ${nodes.length} files it covers are about ${Math.ceil(source / 4)} tokens (${Math.max(1, Math.round(source / 4 / map))}x more to read)`,
  );
}

if (args.includes('--budget')) queryBudget(Number(flag('budget')));
else if (args.includes('--stats')) queryStats();
else if (flag('uses')) queryUses(flag('uses'));
else if (flag('of')) queryOf(flag('of'));
else if (flag('css')) queryCss(flag('css'));
else {
  const graph = render();
  const archFile = path.join(ROOT, ARCH);
  const arch = fs.existsSync(archFile) ? withPlacement(fs.readFileSync(archFile, 'utf8')) : null;
  if (args.includes('--check')) {
    const wanted = [[OUT, graph], ...(arch ? [[ARCH, arch]] : [])];
    const stale = wanted
      .filter(
        ([f, text]) =>
          !fs.existsSync(path.join(ROOT, f)) ||
          fs.readFileSync(path.join(ROOT, f), 'utf8') !== text,
      )
      .map(([f]) => f);
    if (stale.length) {
      console.error(`graph: ${stale.join(' and ')} out of date. Run: ds7 graph`);
      process.exit(1);
    }
    console.log(
      `graph: ${OUT}${arch ? ' and the placement table are' : ' is'} up to date (${nodes.length} nodes)`,
    );
  } else {
    fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
    fs.writeFileSync(path.join(ROOT, OUT), graph);
    if (arch) fs.writeFileSync(archFile, arch);
    console.log(
      `graph: wrote ${OUT} (${graph.split('\n').length} lines, ${nodes.length} nodes)${arch ? ` and the placement table in ${ARCH}` : `; add the lines ${BEGIN} and ${END} to ${ARCH} to get the placement table there`}`,
    );
  }
}
